#!/usr/bin/env python3
"""Turns the original glyph-JSON fonts into odin/game/font_data.odin.

Each row of a glyph is a u16 bit mask, bit x = pixel in column x.
UI font: CyFont5x7, ASCII 32..127, 6 wide, 8 tall.  Tileset: TitsUp.json, glyphs 0..255, 12x12.
"""
import json, sys, os

root = os.path.join(os.path.dirname(__file__), "..")
src = os.path.join(root, "assets", "fonts")


def load(name):
    with open(os.path.join(src, name), encoding="utf-8-sig") as f:
        return json.load(f)


def rows(font, ch):
    g = font["Glyphs"].get(ch)
    out = [0] * font["Height"]
    if g:
        for y, cols in g["Lines"].items():
            for x in cols:
                out[int(y)] |= 1 << x
    return out


ui = load("CyFont5x7.json")
tiles = load("TitsUp.json")
assert {g["Width"] for g in ui["Glyphs"].values()} == {6}
assert {g["Width"] for g in tiles["Glyphs"].values()} == {12}

lines = ["// Generated by tools/gen_fonts.py from the original CyFont5x7.json and TitsUp.json. Do not edit.", "package game", ""]
lines.append(f"UI_FONT_WIDTH :: 6\nUI_FONT_HEIGHT :: {ui['Height']}\nUI_FONT_FIRST :: 32\nUI_FONT_COUNT :: 96\n")
lines.append(f"UI_GLYPHS := [UI_FONT_COUNT][UI_FONT_HEIGHT]u16 {{")
for c in range(32, 128):
    lines.append("\t{" + ", ".join(str(v) for v in rows(ui, chr(c))) + "},")
lines.append("}\n")
lines.append(f"TILE_SIZE :: 12\nTILE_COUNT :: 256\n")
lines.append(f"TILE_GLYPHS := [TILE_COUNT][TILE_SIZE]u16 {{")
for c in range(256):
    lines.append("\t{" + ", ".join(str(v) for v in rows(tiles, chr(c))) + "},")
lines.append("}")
out = os.path.join(root, "odin", "game", "font_data.odin")
with open(out, "w") as f:
    f.write("\n".join(lines) + "\n")
print("wrote", out)
